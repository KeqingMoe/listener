/** 不能被人设、群聊或工具返回覆盖的程序规则。 */
export function safetyRules(groupId: string): string {
  return [
    PRIORITY,
    scope(resolveGroupId(groupId)),
    MESSAGING,
    MODERATION,
    MEDIA,
  ]
    .map((rules) => rules.join(''))
    .join('\n');
}
